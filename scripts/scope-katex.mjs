import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";
import valueParser from "postcss-value-parser";

export function scopeKatexCss(css, namespace) {
  const root = postcss.parse(css);
  const fontFamilies = new Map();

  root.walkAtRules("font-face", (rule) => {
    rule.walkDecls("font-family", (declaration) => {
      const nodes = valueParser(declaration.value).nodes.filter(
        (node) => node.type !== "space" && node.type !== "comment",
      );
      if (nodes.length !== 1 || !["word", "string"].includes(nodes[0].type)) {
        throw new Error(`Unsupported KaTeX font family: ${declaration.value}`);
      }
      const family = nodes[0].value;
      fontFamilies.set(family, `${namespace}-${family}`);
    });
  });

  root.walkRules((rule) => {
    rule.selector = selectorParser((selectors) => {
      selectors.each((selector) => {
        const scope = selectorParser.className({
          value: `${namespace}-math-root`,
        });
        scope.spaces.before = selector.first.spaces.before;
        selector.first.spaces.before = "";
        selector.prepend(selectorParser.combinator({ value: " " }));
        selector.prepend(scope);
      });
    }).processSync(rule.selector);
  });

  root.walkDecls((declaration) => {
    if (!["font-family", "font"].includes(declaration.prop)) return;
    const value = valueParser(declaration.value);
    value.walk((node) => {
      if (node.type === "function") return false;
      if (node.type !== "word" && node.type !== "string") return;
      const family =
        fontFamilies.get(node.value) ??
        (node.value.startsWith("KaTeX_")
          ? `${namespace}-${node.value}`
          : undefined);
      if (family) node.value = family;
    });
    declaration.value = value.toString();
  });

  return root.toString();
}

/**
 * Display-math sizing policy, appended after the scoped KaTeX CSS.
 *
 * `.katex-display` keeps its natural content sizing: `.katex` sizes to
 * `max-content` (but never below the container width) so the equation number
 * slot (`padding-right` on `.katex-html`) is always part of the reported
 * content width. There are deliberately NO per-formula scroll containers —
 * they would hide the true formula width from
 * `syncPopupRenderedTextContainer`, which reads the live overlay's
 * `scrollWidth` to widen the popup so even wide formulas render without
 * scrolling. When a formula is wider than the whole reader, the popup overlay
 * itself (the `.${namespace}-math-root` element, `overflow: auto`) is the
 * single horizontal scroll fallback; its scrollbar is hidden but trackpad
 * panning keeps the equation number reachable.
 */
export function katexDisplayOverflowOverrides(namespace) {
  const root = `.${namespace}-math-root`;
  return `/* ${namespace}: display math sizes to content; the popup widens instead of scrolling per formula. */
${root} {
  scrollbar-width: none;
}
${root} .katex-display {
  padding: 0.15em 0;
}
${root} .katex-display > .katex {
  width: max-content;
  min-width: 100%;
  margin-left: auto;
  margin-right: auto;
}
/* Reserve room for the \\tag number so it never overlaps the formula. */
${root} .katex-display > .katex > .katex-html {
  padding-right: 2.5em;
}
`;
}

export function writeScopedKatexStyles(addonDir, namespace) {
  const path = join(addonDir, "chrome/content/styles/katex.min.css");
  writeFileSync(
    path,
    scopeKatexCss(readFileSync(path, "utf8"), namespace) +
      katexDisplayOverflowOverrides(namespace),
  );
}

/**
 * Emit a TypeScript module exporting the scoped KaTeX CSS with fonts embedded
 * as data: URIs. The reader renders in a resource:// document where chrome://
 * <link> stylesheets are blocked, so the plugin injects this CSS inline.
 */
export function writeInlineKatexModule(addonDir, namespace, modulePath) {
  const styleDir = join(addonDir, "chrome/content/styles");
  let css = readFileSync(join(styleDir, "katex.min.css"), "utf8");
  css = css.replace(/url\((fonts\/[^)]+)\)/g, (_, fontPath) => {
    const data = readFileSync(join(styleDir, fontPath)).toString("base64");
    return `url(data:font/woff2;base64,${data})`;
  });
  const escaped = css
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  writeFileSync(
    modulePath,
    `// AUTO-GENERATED by scripts/scope-katex.mjs — do not edit.\n` +
      `// Scoped KaTeX CSS with data-URI fonts for inline injection.\n` +
      `export const KATEX_SCOPED_CSS = \`${escaped}\`;\n`,
  );
}
